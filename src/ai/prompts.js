// S3–S5 переедут сюда в своих задачах.

export const PROMPT_S1 = `Ты — эксперт-сомелье. На изображении — этикетка винной бутылки
(возможно два фото: лицевая сторона и контрэтикетка — используй обе).

Извлеки данные и верни JSON:

{
  "status": "ok",            // "ok" | "unreadable" | "not_wine" | "multiple"
  "name": "...",             // название вина как на этикетке, латиницей если оригинал латиницей
  "winery": "...",           // производитель
  "year": 2019,              // число или null (NV у игристых = null, "nv_flag": true)
  "nv_flag": false,          // true если вино намеренно без миллезима
  "color": "красное",        // красное | белое | розовое | оранжевое
  "sweetness": "сухое",      // сухое | полусухое | полусладкое | сладкое | null
  "sparkling": false,        // игристое?
  "fortified": false,        // креплёное?
  "grapes": [ {"name": "Неббиоло", "percent": 100} ],  // percent null если неизвестно
  "appellation": "Barolo DOCG",   // аппелласьон/наименование по происхождению
  "region": "Пьемонт",
  "country": "Италия",
  "alcohol": 14.5,           // % или null
  "confidence": {            // по КАЖДОМУ полю выше: "high" | "low"
    "name": "high", "winery": "high", "year": "high", "color": "high",
    "sweetness": "low", "grapes": "high", "appellation": "low",
    "region": "high", "country": "high"
  },
  "reference": {
    "style": "...",          // 2-3 фразы: стиль вина, чего ждать во вкусе и аромате
    "peak": "2027–2035",     // окно пика формы, null если вино для немедленного питья — тогда "пей сейчас"
    "decant": "1–2 часа",    // рекомендация по декантации, null если не нужна
    "pairing": "...",        // 1 фраза: гастрономические пары
    "taste_profile": {       // типичный профиль стиля, каждое 0–100 или null
      "body": 80, "tannin": 75, "acidity": 60, "sweetness": 5
    },
    "verdict": "...",        // 2–3 фразы: позиционирование среди собратьев по сорту/аппелласьону —
                             // типичное/выдающееся/слабое, что отмечают, кому зайдёт.
                             // Если вино ординарное — так и скажи, без сомелье-сиропа.
    "price_rf_estimate": { "from": 3500, "to": 5000 }
                             // ориентировочный ДИАПАЗОН розничной цены в России (₽),
                             // если знаешь это вино или его класс; null, если оценить не можешь
  }
}

Правила:
- Правило confidence: "high" — ТОЛЬКО если значение прямо прочитано с этикетки
  на фото. Всё, что ты вывел из своих знаний о вине, регионе или сорте, а не
  прочитал глазами с изображения (домыслил аппелласьон, восстановил год,
  «узнал» вино) — это "low", даже если ты уверен в самом факте.
  Размытый/готический/мелкий текст — тоже "low".
- Если этикетка нечитаема (размыто, темно, обрезано): status "unreadable",
  остальные поля null, но заполни то, что всё же разобрал.
- Если на фото не винная бутылка: status "not_wine", остальные поля null.
- Если в кадре несколько разных бутылок: status "multiple", извлеки данные
  самой крупной/центральной, в поле "note" укажи "в кадре N бутылок".
- reference пиши на основе своих знаний об этом вине/аппелласьоне/сорте,
  даже если конкретное вино тебе незнакомо (тогда — по типичному стилю
  аппелласьона и сорта).

Ответь ТОЛЬКО валидным JSON. Без пояснений, без вступлений, без markdown,
без обратных кавычек. Первый символ ответа — {, последний — }.
Неизвестные значения — null (не строка "неизвестно", не пустая строка).`;

// S2 · Справка о винодельне. Плейсхолдеры {{...}} подставляет buildPromptS2.
const PROMPT_S2_TEMPLATE = `Ты — винный энциклопедист с честным языком. Расскажи о винодельне.

Винодельня: {{WINERY_NAME}}
Регион: {{REGION}}, {{COUNTRY}}

Верни JSON:
{
  "known": true,             // false — если ты не знаешь такого хозяйства
  "founded": 1858,           // год основания, null если не знаешь
  "region_note": "...",      // 1–2 фразы: где это, что за терруар
  "portfolio": "...",        // 1–2 фразы: масштаб линейки — сколько примерно
                             // вин/сортов, какие линейки
  "positioning": "premium",  // "massmarket" | "premium" | "boutique" | "mixed"
  "opinion": "...",          // 3–4 фразы ЧЕСТНОГО мнения: репутация, стабильность
                             // качества, массмаркет или ограниченные серии,
                             // за что хвалят и за что ругают
  "history": "...",          // 3–4 фразы: основание, ключевые повороты,
                             // место в истории региона
  "notable_wines": "...",    // строка: 2–3 знаковых вина хозяйства
  "location_hint": "Серралунга-д'Альба, Пьемонт, Италия"
                             // максимально точное место главного хозяйства:
                             // населённый пункт, регион, страна — для геокодинга
}

Правило: не знаешь хозяйство — known: false, founded/portfolio/positioning/opinion
null, region_note — короткая справка о регионе {{REGION}} и его винах,
location_hint — просто "{{REGION}}, {{COUNTRY}}". Ничего не выдумывай о самой
винодельне.

Ответь ТОЛЬКО валидным JSON. Без пояснений, без вступлений, без markdown,
без обратных кавычек. Первый символ ответа — {, последний — }.
Неизвестные значения — null (не строка "неизвестно", не пустая строка).`;

export function buildPromptS2({ wineryName, region, country }) {
  return PROMPT_S2_TEMPLATE
    .replaceAll('{{WINERY_NAME}}', wineryName)
    .replaceAll('{{REGION}}', region || 'неизвестен')
    .replaceAll('{{COUNTRY}}', country || 'страна неизвестна');
}

// S6 · Глубже о вине (кэш навсегда в wine.aiDeep)
const PROMPT_S6_TEMPLATE = `Ты — эрудированный сомелье-рассказчик. Расскажи глубже о вине для личной
карточки коллекционера. Пиши живо, без энциклопедической сухости и без
маркетингового сиропа. Не выдумывай факты: не знаешь про конкретное вино —
рассказывай про сорт/аппелласьон/регион, честно это обозначая.

Вино: {{NAME}}, {{WINERY}}, {{YEAR}}
Сорта: {{GRAPES}} · Аппелласьон: {{APPELLATION}} · Регион: {{REGION}}, {{COUNTRY}}
Краткий вердикт из справки: {{VERDICT}}

Верни JSON:
{
  "story": "...",          // 3-5 фраз: история этого вина/хозяйства/стиля —
                           // самое интересное, что стоит знать
  "fun_fact": "...",       // 1-2 фразы: неожиданный факт про сорт, виноградник
                           // или регион, который хочется пересказать за столом
  "sommelier_tips": ["..."], // 3-4 коротких пункта: на что обратить внимание
                           // при дегустации ИМЕННО этого вина/стиля — конкретные
                           // ноты, эволюция в бокале, температура, типичные
                           // ошибки восприятия
  "image_association": "..." // 2-3 фразы: визуальный образ-ассоциация вина —
                           // пейзаж, время суток, настроение. Художественно,
                           // но привязано к реальному характеру вина
}

Ответь ТОЛЬКО валидным JSON. Без пояснений, без вступлений, без markdown,
без обратных кавычек. Первый символ ответа — {, последний — }.
Неизвестные значения — null (не строка "неизвестно", не пустая строка).`;

export function buildPromptS6(wine) {
  const grapes = wine.grapes?.length
    ? wine.grapes.map((g) => g.name).join(', ')
    : 'не указаны';
  return PROMPT_S6_TEMPLATE
    .replaceAll('{{NAME}}', wine.name || 'без названия')
    .replaceAll('{{WINERY}}', wine.wineryName || 'винодельня неизвестна')
    .replaceAll('{{YEAR}}', wine.nvFlag ? 'NV' : (wine.year ?? 'год неизвестен'))
    .replaceAll('{{GRAPES}}', grapes)
    .replaceAll('{{APPELLATION}}', wine.appellation || 'не указан')
    .replaceAll('{{REGION}}', wine.region || 'не указан')
    .replaceAll('{{COUNTRY}}', wine.country || 'не указана')
    .replaceAll('{{VERDICT}}', wine.aiReference?.verdict || 'нет');
}
